# Ask for two numbers and print their sum, difference, product, and division.

number1 = int(input("Enter a number: "))
number2 = int(input("Enter another number: "))

add=number1 + number2
print("The sum of", number1, "and", number2, "is", add)

subtraction=number1 - number2
print("The difference of", number1, "and", number2, "is", subtraction)  

multiplication=number1 * number2
print("The product of", number1, "and", number2, "is", multiplication)  

division=number1 / number2
print("The quotient of", number1, "and", number2, "is", division )